from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / ".build" / "run.lua"

SOURCES = {
    "server": ROOT / "src" / "ServerScriptService" / "Flux" / "init.server.lua",
    "client": ROOT / "src" / "StarterPlayer" / "StarterPlayerScripts" / "Flux" / "init.client.lua",
    "require": ROOT / "src" / "ReplicatedStorage" / "Packages" / "require" / "init.lua",
    "asset": ROOT / "src" / "ReplicatedStorage" / "Packages" / "asset" / "init.lua",
    "element": ROOT / "src" / "ReplicatedStorage" / "Packages" / "element" / "init.lua",
    "quality": ROOT / "src" / "ReplicatedStorage" / "Packages" / "quality" / "init.lua",
    "tagged": ROOT / "src" / "ReplicatedStorage" / "Packages" / "tagged" / "init.lua",
    "tween": ROOT / "src" / "ReplicatedStorage" / "Packages" / "tween" / "init.lua",
}


def long_string(text: str) -> str:
    for equals in range(0, 12):
        marker = "]" + ("=" * equals) + "]"
        if marker not in text:
            opening = "[" + ("=" * equals) + "["
            return opening + text + marker
    raise ValueError("could not find a safe long-string delimiter")


def main() -> None:
    parts = ["-- Generated by tests/build.py. Do not edit.", "", "local Sources = {}"]
    for name, path in SOURCES.items():
        source = path.read_text(encoding="utf-8")
        parts.append(f"Sources.{name} = {long_string(source)}")
        parts.append("")
    parts.append((ROOT / "tests" / "mock.lua").read_text(encoding="utf-8"))
    parts.append("")
    parts.append((ROOT / "tests" / "spec.lua").read_text(encoding="utf-8"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
